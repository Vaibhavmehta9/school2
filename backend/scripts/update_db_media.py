db_paths = [
    os.path.join(os.path.dirname(__file__), "..", "sheerwood.db"),
    os.path.join(os.path.dirname(__file__), "..", "sheerwood.demo.db"),
]

for db_path in db_paths:
    if not os.path.exists(db_path):
        print(f"Skipping {db_path} (not found)")
        continue
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()
    table_check = cur.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='media_items'").fetchone()
    if not table_check:
        print(f"Skipping {db_path} (table media_items does not exist)")
        conn.close()
        continue
    cur.execute("DELETE FROM media_items")
    print(f"Cleared existing media_items in {db_path}")

    for it in items:
        cur.execute(
            """
            INSERT INTO media_items (
                id, kind, title, slug, summary, description, category, chapter_order,
                start_at, end_at, all_day, location, video_provider, video_id, video_url,
                video_embed_url, video_poster_url, cover_image_path, duration_seconds,
                link_url, link_label, status, featured, sort_order, demo, source_credit,
                has_students, consent_confirmed
            ) VALUES (
                :id, :kind, :title, :slug, :summary, :description, :category, :chapter_order,
                :start_at, :end_at, :all_day, :location, :video_provider, :video_id, :video_url,
                :video_embed_url, :video_poster_url, :cover_image_path, :duration_seconds,
                :link_url, :link_label, :status, :featured, :sort_order, :demo, :source_credit,
                :has_students, :consent_confirmed
            )
            """,
            it
        )
    conn.commit()
    conn.close()
    print(f"Successfully seeded {len(items)} official channel media items into {db_path}")
